const insideStringLiteral = (tail) => /\\[nr]/.test(tail);

function unexplainedDirectives(text) {
  if (GENERATED.test(text)) return [];
  const found = [];
  for (const match of text.matchAll(DIRECTIVE)) {
    if (insideStringLiteral(match[2])) continue;
    const [rules, reason = ""] = match[2].split(/\s--(?:\s|$)/);
    if (reason.trim()) continue;
    found.push({
      line: text.slice(0, match.index).split("\n").length,
      directive: match[1],
      rules: rules.trim() || "(all rules)",
    });
  }
  return found;
}

function findProblems(files, read, baseline = UNEXPLAINED_BASELINE, { full = true } = {}) {
  const remaining = { ...baseline };
  const problems = [];
  for (const file of files) {
    if (!SOURCE.test(file) || SKIPPED.some((pattern) => pattern.test(file))) continue;
    for (const { line, directive, rules } of unexplainedDirectives(read(file))) {
      const key = `${file} ${rules}`;
      if (remaining[key] > 0) remaining[key] -= 1;
      else problems.push(`${file}:${line} ${directive} ${rules} has no "-- <reason>"`);
    }
  }
  if (full)
    for (const [key, count] of Object.entries(remaining))
      if (count > 0) problems.push(`${key}: ${count} fewer unexplained suppression(s) than the baseline; lower it in scripts/check-suppressions.cjs`);
  return problems;
}

function main(argv) {
  const root = path.resolve(__dirname, "..");
  const full = argv.length === 0;
  const files = full
    ? execFileSync("git", ["ls-files", "-z"], { cwd: root, encoding: "utf8" }).split("\0").filter(Boolean)
    : argv.map((file) => path.relative(root, path.resolve(file)).split(path.sep).join("/"));
  const read = (file) => {
    try {
      return fs.readFileSync(path.join(root, file), "utf8");
    } catch {
      return "";
    }
  };
  const problems = findProblems(files, read, UNEXPLAINED_BASELINE, { full });
  if (!problems.length) return 0;
  console.error(
    `${problems.map((problem) => `  ${problem}`).join("\n")}\n\n` +
      "A lint suppression says why: // oxlint-disable-next-line <rule> -- <why the rule is wrong here>.\n" +
      "Keep one only when the rule is faulty, pedantic or style-only for that line; otherwise fix the code.",
  );
  return 1;
}

if (require.main === module) process.exit(main(process.argv.slice(2)));

module.exports = { unexplainedDirectives, findProblems, UNEXPLAINED_BASELINE };
