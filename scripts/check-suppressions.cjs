const GENERATED = /^\/\/ Generated by .*Do not edit\./;
const DIRECTIVE = /(?:\/\/|\/\*)\s*((?:eslint|oxlint)-disable(?:-next-line|-line)?)\b(.*?)(?:\*\/|$)/gm;

