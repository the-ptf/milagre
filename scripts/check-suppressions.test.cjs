const test = require("node:test");
const assert = require("node:assert/strict");
const { spawnSync } = require("node:child_process");
const path = require("node:path");
const { unexplainedDirectives, findProblems } = require("./check-suppressions.cjs");

const disable = (kind) => `oxlint-${kind}`;
const NEXT_LINE = disable("disable-next-line");

test("a suppression with a reason passes in every comment form", () => {
  const text = [
    `// ${NEXT_LINE} no-control-regex -- XML 1.0 excludes these controls`,
    `const a = 1; // eslint-disable-line no-shadow -- shadowing is the point here`,
    `/* ${disable("disable")} no-misleading-character-class -- each combining character stands alone */`,
  ].join("\n");
  assert.deepEqual(unexplainedDirectives(text), []);
});

test("a suppression without a reason is reported with its line and rules", () => {
  const text = ["const a = 1;", `// ${NEXT_LINE} unicorn/no-array-sort`, `/* ${disable("disable")} */`, "x(); // eslint-disable-line no-console --"].join("\n");
  assert.deepEqual(unexplainedDirectives(text), [
    { line: 2, directive: NEXT_LINE, rules: "unicorn/no-array-sort" },
    { line: 3, directive: disable("disable"), rules: "(all rules)" },
    { line: 4, directive: "eslint-disable-line", rules: "no-console" },
  ]);
});

test("prose about a directive, string fixtures and generated files are not suppressions", () => {
  assert.deepEqual(unexplainedDirectives(`// a reason follows ${NEXT_LINE} in our rule`), []);
  assert.deepEqual(unexplainedDirectives("const fixture = `// " + NEXT_LINE + "\\nconst b = 1;`;"), []);
  assert.deepEqual(unexplainedDirectives(`// Generated by scripts/x.mjs. Do not edit.\n// ${NEXT_LINE} foo`), []);
});

test("the baseline absorbs known suppressions, rejects new ones and must shrink when one is fixed", () => {
  const files = { "a.ts": `// ${NEXT_LINE} foo\n// ${NEXT_LINE} foo`, "b.md": `// ${NEXT_LINE} foo`, "dist/c.js": `// ${NEXT_LINE} foo` };
  const read = (file) => files[file];
  assert.deepEqual(findProblems(Object.keys(files), read, { "a.ts foo": 2 }), []);
  assert.deepEqual(findProblems(Object.keys(files), read, { "a.ts foo": 1 }), ['a.ts:2 oxlint-disable-next-line foo has no "-- <reason>"']);
  assert.match(findProblems(Object.keys(files), read, { "a.ts foo": 3 })[0], /a\.ts foo: 1 fewer unexplained suppression/);
  assert.deepEqual(findProblems(["a.ts"], read, { "a.ts foo": 3 }, { full: false }), []);
});

test("every tracked source file passes", () => {
  const result = spawnSync(process.execPath, [path.join(__dirname, "check-suppressions.cjs")], { encoding: "utf8" });
  assert.equal(result.status, 0, result.stderr);
});
