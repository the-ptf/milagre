// Triage sessions: the playbook and a file of machine facts, written to a fresh folder, for a coding agent that diagnoses
// a misbehaving install and helps file an issue. `milagre triage` (apps/daemon/src/triage.cjs) and the in-app
// "Triage an issue" entry (the triage:prepare command) both start from these files. Modeled on T3 Code's `t3 triage`.
const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");
const { resolveExecutable } = require("./agents/environment.cjs");

const AGENTS = [
  { id: "claude", label: "Claude Code" },
  { id: "codex", label: "Codex" },
];
// Files holding keys, tokens or pairing secrets. The agent never reads them.
const SECRET_FILES = [
  "computer-keys.json",
  "computer-vault.json",
  "computer-vault-key.json",
  "relay-identity.json",
  "devices.json",
  "mobile.json",
  "mobile-push.json",
  "local-mcp",
  "linear",
  "accounts",
];

const IN_APP = `
## This session runs inside Milagre

You are a Chat inside the host described below. Stopping, restarting or killing that host, or quitting the desktop app,
ends this session. When a fix needs one of those, give the user the exact steps and let them do it. The host has its
files open: read them, never lock them.
`;

/** @param {{ kind: "cli"; cliVersion: string; launchedAs: string } | { kind: "app"; client: string }} entry */
function entryLines(entry) {
  return entry.kind === "cli"
    ? [
        `- Triage CLI version: ${entry.cliVersion} (the \`milagre\` npm package that ran this command, not the desktop app's version)`,
        `- CLI launched as: ${entry.launchedAs}`,
      ]
    : [`- Started from: ${entry.client} (where the user chose "Triage an issue"; the bug may have happened on another device)`];
}

/**
 * @param {{ generatedAt: string; entry: any; agents: { id: string; path: string | null }[]; sourceCacheDir: string;
 *   profiles: { label: string; dir: string; exists: boolean; host?: string }[] }} input
 */
function buildContext({ generatedAt, entry, profiles, agents, sourceCacheDir }) {
  const profileLines = profiles.map((profile) =>
    profile.exists
      ? [
          `### ${profile.label}`,
          "",
          `- Profile: ${profile.dir}`,
          `- Host: ${profile.host}`,
          `- Host log: ${path.join(profile.dir, "daemon.log")}`,
          `- Ownership lock: ${path.join(profile.dir, "runtime.lock", "owner.json")}`,
          `- Secret files (NEVER read these): ${SECRET_FILES.map((name) => path.join(profile.dir, name)).join(", ")}`,
        ].join("\n")
      : `### ${profile.label}\n\n- Profile: ${profile.dir} (does not exist on this computer)`,
  );
  return `# Milagre triage context

Generated by ${entry.kind === "cli" ? "`milagre triage`" : "the Milagre app"} at ${generatedAt}.

${entryLines(entry).join("\n")}
- OS: ${process.platform} ${process.arch} (${os.release()})
- Node: ${process.version}
- Agent CLIs: ${agents.map((agent) => `${agent.id} ${agent.path ?? "not found on PATH"}`).join("; ")}
- Repo: https://github.com/the-ptf/milagre-ade
- Source cache dir (clone the repo here): ${sourceCacheDir}
${entry.kind === "app" ? IN_APP : ""}
## Profiles

${profileLines.join("\n\n")}
`;
}

const findAgents = () => Promise.all(AGENTS.map(async (agent) => Object.assign({}, agent, { path: await resolveExecutable(agent.id) })));

/** Writes PLAYBOOK.md and context.md into `<root>/<time>/`. */
async function writeTriageSession({ root, entry, profiles, agents }) {
  const sessionDir = path.join(root, new Date().toISOString().replace(/[:.]/g, "-"));
  fs.mkdirSync(sessionDir, { recursive: true, mode: 0o700 });
  const playbookPath = path.join(sessionDir, "PLAYBOOK.md");
  const contextPath = path.join(sessionDir, "context.md");
  fs.copyFileSync(path.join(__dirname, "triage-playbook.md"), playbookPath);
  const context = buildContext({
    generatedAt: new Date().toISOString(),
    entry,
    profiles,
    agents: agents ?? (await findAgents()),
    sourceCacheDir: path.join(root, "source"),
  });
  fs.writeFileSync(contextPath, context, { mode: 0o600 });
  return { sessionDir, playbookPath, contextPath };
}

/**
 * The in-app entry: a session beside this host's own profile, and the draft its new Chat opens with. The user writes
 * what went wrong after it, so the first turn already carries the description.
 * @param {{ dataDir: string; version: string; client?: unknown }} input
 */
async function prepareTriage({ dataDir, version, client }) {
  const { playbookPath } = await writeTriageSession({
    root: path.join(dataDir, "triage"),
    entry: { kind: "app", client: typeof client === "string" && client.trim() ? client.trim().slice(0, 200) : "an unknown client" },
    profiles: [{ label: "This host", dir: dataDir, exists: true, host: `running (pid ${process.pid}, version ${version}); this session runs inside it` }],
  });
  return { prompt: `Read ${playbookPath} and follow it. What went wrong: ` };
}

module.exports = { AGENTS, SECRET_FILES, buildContext, findAgents, writeTriageSession, prepareTriage };
