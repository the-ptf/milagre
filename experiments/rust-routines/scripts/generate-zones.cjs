// Reproducible ICU alias inventory from the exact tested Node, not timezone transitions.
const fs = require("node:fs");
const input = JSON.parse(fs.readFileSync(0, "utf8"));
if (input.version !== "2025b" || process.versions.tz !== "2025b" || process.versions.icu !== "77.1") throw Error("Timezone oracle drift");
const all = new Set([...input.names, ...Intl.supportedValuesOf("timeZone"), "UTC", "GMT", "US/Pacific-New", "Canada/East-Saskatchewan"]);
const entries = [...all]
  .sort()
  .flatMap((name) => {
    try {
      return [[name.toLowerCase(), new Intl.DateTimeFormat("en-US", { timeZone: name }).resolvedOptions().timeZone]];
    } catch {
      return [];
    }
  })
  .sort((a, b) => a[0].localeCompare(b[0], "en"));
entries.sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0));
console.log("// Generated by scripts/generate-zones.cjs from Node ICU 77.1 / TZDB 2025b.");
console.log("pub(super) const NAMES: &[(&str, &str)] = &[");
for (const [name, canonical] of entries) console.log(`    (${JSON.stringify(name)}, ${JSON.stringify(canonical)}),`);
console.log("];");
