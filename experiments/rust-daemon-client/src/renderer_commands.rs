pub(crate) fn allowed(method: &str) -> Option<&'static str> {
    if method == "app-update:install" {
        return None;
    }
    RENDERER_COMMANDS
        .binary_search(&method)
        .ok()
        .map(|index| RENDERER_COMMANDS[index])
}
