// Generates the design layout's data from the desktop's own modules in packages/shared/src, and the parity vectors
// the Rust tests check against. Run from experiments/rust-gpui: `node src/logic/design_layout/generate.mjs`.
//
// Writes:
// - src/logic/design_layout/data.json: advance tables (generic kinds, Inter, the catalog), the NFD base letter of
//   characters whose decomposition changes their fallback advance, the combining marks, and the CSS colour names.
// - src/workspace/panel/designs/data/lucide.json and inter-<weight>.ttf: the icons and the embedded Inter faces.
// - src/logic/design_layout/vectors.json: designLayout, designTextLayout and designNodeAt run on the cases in
//   cases.json and on every fixture design, through validateDesignDocument (kits resolved as the host does).
//
// validateDesignDocument needs zod, which this worktree may not have installed: the shared modules are copied to a
// temporary folder beside a link to a node_modules that has it (MILAGRE_NODE_MODULES, else the main checkout's).
import { cpSync, existsSync, mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, symlinkSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { execFileSync } from "node:child_process";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const crate = resolve(here, "../../..");
const repo = resolve(crate, "../..");
const shared = join(repo, "packages/shared/src");
const designsData = join(crate, "src/workspace/panel/designs/data");
const fixtureDir = join(crate, "src/workspace/panel/designs/fixture");

function nodeModules() {
  if (process.env.MILAGRE_NODE_MODULES) return process.env.MILAGRE_NODE_MODULES;
  if (existsSync(join(repo, "node_modules/zod"))) return join(repo, "node_modules");
  const common = execFileSync("git", ["rev-parse", "--path-format=absolute", "--git-common-dir"], { cwd: repo, encoding: "utf8" }).trim();
  return join(dirname(common), "node_modules");
}

const work = mkdtempSync(join(tmpdir(), "design-layout-"));
try {
  mkdirSync(join(work, "src"));
  for (const name of readdirSync(shared))
    if (/\.(mjs|json)$/.test(name) || name === "design-catalog-fonts") cpSync(join(shared, name), join(work, "src", name), { recursive: true });
  writeFileSync(join(work, "package.json"), '{"type":"module"}');
  symlinkSync(nodeModules(), join(work, "node_modules"));
  const load = (name) => import(pathToFileURL(join(work, "src", name)).href);
  const { designFontMetrics } = await load("design-font-metrics.mjs");
  const { DESIGN_FONT_CATALOG } = await load("design-font-catalog.mjs");
  const { DESIGN_EXTRA_CHARACTERS } = await load("design-font-characters.mjs");
  const { namedColors } = await load("design-color-names.mjs");
  const { designIcons } = await load("design-icons.mjs");
  const { designInterFonts } = await load("design-font-data.mjs");
  const { designLayout, designTextLayout } = await load("design-layout.mjs");
  const design = await load("design.mjs");

  // What designTextLayout's fallback advance reads for a character: the first code point of its NFD form with the
  // marks removed. Kept as ranges, and only where it changes the advance: an ASCII base (its own advance), no base
  // left (0), or a base on the other side of U+2E80 (1 em against 0.65 em; Hangul syllables decompose to jamo).
  const bases = [];
  const marks = [];
  const wide = (point) => point >= 0x2e80;
  const push = (list, point, value) => {
    const last = list.at(-1);
    if (last && last[1] === point - 1 && last[2] === value) last[1] = point;
    else list.push([point, point, value]);
  };
  for (let point = 0xa0; point <= 0x10ffff; point++) {
    if (point >= 0xd800 && point <= 0xdfff) continue;
    const character = String.fromCodePoint(point);
    if (/\p{M}/u.test(character)) push(marks, point, 1);
    const base = character.normalize("NFD").replace(/\p{M}/gu, "").codePointAt(0);
    if (base === point) continue;
    if (base === undefined) push(bases, point, -1);
    else if (base >= 32 && base <= 126) push(bases, point, base);
    else if (wide(base) !== wide(point)) push(bases, point, wide(base) ? 0x2e80 : 0xa0);
  }
  const extra = Array.from(DESIGN_EXTRA_CHARACTERS, (character) => character.codePointAt(0));
  const catalog = Object.fromEntries(
    Object.entries(DESIGN_FONT_CATALOG).map(([key, entry]) => [key, { family: entry.family, weights: entry.weights, advances: entry.advances }]),
  );
  const data = {
    note: "Generated by generate.mjs from packages/shared/src; do not edit.",
    metrics: designFontMetrics,
    catalog,
    extra,
    bases,
    marks: marks.map(([from, to]) => [from, to]),
    colors: namedColors,
  };
  writeFileSync(join(here, "data.json"), JSON.stringify(data));

  writeFileSync(join(designsData, "lucide.json"), JSON.stringify(designIcons));
  for (const [weight, base64] of Object.entries(designInterFonts)) writeFileSync(join(designsData, `inter-${weight}.ttf`), Buffer.from(base64, "base64"));
  cpSync(join(shared, "design-icons.LICENSE.txt"), join(designsData, "LUCIDE-LICENSE.txt"));
  cpSync(join(shared, "design-font-data.LICENSE.txt"), join(designsData, "INTER-LICENSE.txt"));

  // Parity vectors.
  const cases = JSON.parse(readFileSync(join(here, "cases.json"), "utf8"));
  for (const name of readdirSync(fixtureDir)
    .filter((file) => file.endsWith(".json"))
    .sort()) {
    const fixture = JSON.parse(readFileSync(join(fixtureDir, name), "utf8"));
    fixture.versions.forEach((document, index) => cases.push({ name: `fixture ${fixture.id} v${index + 1}`, document, points: [] }));
  }
  const vectors = cases.map(({ name, document, points = [] }) => {
    const checked = design.validateDesignDocument(structuredClone(document));
    const bounds = designLayout(checked);
    const texts = {};
    for (const node of checked.nodes) {
      const box = bounds.get(node.id);
      if (node.type !== "text" || !box) continue;
      const stroke = node.stroke ? (node.strokeWidth ?? 1) : 0;
      texts[node.id] = { natural: designTextLayout(node), boxed: designTextLayout(node, Math.max(1, box.width - 2 * stroke)) };
    }
    // Points on a grid over the screen plus the case's own, for the hit test.
    const grid = [];
    for (let gx = 1; gx < 8; gx++) for (let gy = 1; gy < 12; gy++) grid.push([(checked.width * gx) / 8, (checked.height * gy) / 12]);
    const hits = [...points, ...grid].map(([x, y]) => [x, y, design.designNodeAt(checked, x, y)?.id ?? null]);
    return { name, document, bounds: [...bounds].map(([id, box]) => [id, box.x, box.y, box.width, box.height]), texts, hits };
  });
  writeFileSync(join(here, "vectors.json"), JSON.stringify({ note: "Generated by generate.mjs; do not edit.", vectors }, null, 1));
  console.log(
    `data.json, lucide.json (${Object.keys(designIcons).length} icons), ${Object.keys(designInterFonts).length} Inter faces, ${vectors.length} vector documents`,
  );
} finally {
  rmSync(work, { recursive: true, force: true });
}
