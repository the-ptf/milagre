/// `Math.round(value * 1000) / 1000`: thousandths, halves rounded up as JavaScript does (Rust rounds them away from
/// zero).
pub fn js_round(value: f64) -> f64 {
    let scaled = value * 1000.0;
    let floor = scaled.floor();
    (if scaled - floor >= 0.5 { floor + 1.0 } else { floor }) / 1000.0
}

/// `designDefaultFill`: what a layer paints when it names no fill. Frames, and images with a source, stay clear.
pub fn default_fill(node: &DesignNode) -> &'static str {
    match node.kind {
        NodeType::Text | NodeType::Icon => DESIGN_INK,
        NodeType::Frame => "transparent",
        NodeType::Image if node.src.is_some() => "transparent",
        _ => DESIGN_PLACEHOLDER,
    }
}

/// `visibleDesignTextLines`: the lines a text box shows, keeping a partly visible last line and the overhang of a
/// short line height.
pub fn visible_lines<'a>(node: &DesignNode, bounds: &Bounds, text: &'a TextLayout) -> &'a [String] {
    let height = (bounds.height - 2.0 * node.border()).max(0.0);
    if height == 0.0 {
        return &[];
    }
    let overhang = ((node.font_size() - text.line_height) / 2.0).max(0.0);
    let count = ((height + overhang) / text.line_height).ceil() as usize;
    &text.lines[..count.min(text.lines.len())]
}
